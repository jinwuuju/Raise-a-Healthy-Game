# coding: utf-8
"""Build a dependency-free static design library. Only allowlisted files leave the repo."""
import html
import json
import os
import re
import shutil
from pathlib import Path
from urllib.parse import unquote, urlparse
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / '_site'
REPO = 'https://github.com/jinwuuju/Raise-a-Healthy-Game'
SOURCES = [ROOT / 'README.md'] + sorted((ROOT / 'docs').rglob('*.md')) + [ROOT / 'LICENSE', ROOT / 'THIRD_PARTY_NOTICES.md']

def slug(path):
    return '-'.join(path.relative_to(ROOT).with_suffix('').parts).lower().replace('_', '-') + '.html'

ROUTES = {path.resolve(): 'read/' + slug(path) for path in SOURCES}

def resolve_link(url, source):
    parsed = urlparse(url)
    if parsed.scheme:
        return url if parsed.scheme in ('https', 'http', 'mailto') else '#'
    if url.startswith('#'):
        return url
    local = (source.parent / unquote(parsed.path)).resolve()
    if local in ROUTES:
        dest = ROUTES[local]
    elif local.is_relative_to(ROOT / 'data') and local.is_file():
        dest = local.relative_to(ROOT).as_posix()
    else:
        try:
            return REPO + '/blob/main/' + local.relative_to(ROOT).as_posix()
        except ValueError:
            return '#'
    return '../' + dest + ('#' + parsed.fragment if parsed.fragment else '')

def inline(text, source):
    # Escape first. Insert only a small, explicit set of formatting elements.
    tokens = []
    def hold(markup):
        tokens.append(markup)
        return f'@@TOKEN{len(tokens)-1}@@'
    text = re.sub(r'`([^`]+)`', lambda m: hold('<code>'+html.escape(m[1])+'</code>'), text)
    text = re.sub(r'\[([^\]]+)\]\(([^\s)]+)\)', lambda m: hold('<a href="'+html.escape(resolve_link(m[2], source), quote=True)+'">'+html.escape(m[1])+'</a>'), text)
    text = html.escape(text)
    text = re.sub(r'\*\*([^*]+)\*\*', r'<strong>\1</strong>', text)
    for i, token in enumerate(tokens):
        text = text.replace(f'@@TOKEN{i}@@', token)
    return text

def markdown(text, source):
    lines = text.splitlines(); out = []; i = 0
    while i < len(lines):
        line = lines[i].strip()
        if not line:
            i += 1; continue
        if line.startswith('```'):
            i += 1; block = []
            while i < len(lines) and not lines[i].strip().startswith('```'):
                block.append(lines[i]); i += 1
            out.append('<pre><code>'+html.escape('\n'.join(block))+'</code></pre>'); i += 1; continue
        heading = re.match(r'^(#{1,6})\s+(.+)$', line)
        if heading:
            n = len(heading[1]); out.append(f'<h{n}>'+inline(heading[2],source)+f'</h{n}>'); i += 1; continue
        if line.startswith('|'):
            table=[]
            while i<len(lines) and lines[i].strip().startswith('|'):
                cells=[c.strip() for c in lines[i].strip().strip('|').split('|')]
                if not all(re.fullmatch(r':?-+:?',c.replace(' ','')) for c in cells):table.append(cells)
                i+=1
            out.append('<div class="table-wrap" tabindex="0" role="region" aria-label="가로로 스크롤할 수 있는 설계 표"><table>')
            for j,row in enumerate(table):
                tag='th' if j==0 else 'td'; out.append('<tr>'+''.join(f'<{tag}>'+inline(c,source)+f'</{tag}>' for c in row)+'</tr>')
            out.append('</table></div>');continue
        if line.startswith('>'):
            block=[]
            while i<len(lines) and lines[i].lstrip().startswith('>'):
                block.append(lines[i].lstrip()[1:].strip());i+=1
            out.append('<blockquote>'+inline(' '.join(block),source)+'</blockquote>');continue
        item = re.match(r'^(?:[-*]|\d+\.)\s+(.+)$',line)
        if item:
            ordered=bool(re.match(r'^\d+\.',line));tag='ol' if ordered else 'ul';out.append('<'+tag+'>')
            while i<len(lines):
                m=re.match(r'^(?:[-*]|\d+\.)\s+(.+)$',lines[i].strip())
                if not m:break
                out.append('<li>'+inline(m[1],source)+'</li>');i+=1
            out.append('</'+tag+'>');continue
        para=[line];i+=1
        while i<len(lines) and lines[i].strip() and not re.match(r'^(#|\||>|```|[-*] |\d+\. )',lines[i].strip()):
            para.append(lines[i].strip());i+=1
        out.append('<p>'+inline(' '.join(para),source)+'</p>')
    return '\n'.join(out)

def main():
    OUT.mkdir(exist_ok=True)
    # Remove only files generated by the previous builder invocation.
    manifest=OUT/'build-manifest.json'
    if manifest.exists():
        for item in json.loads(manifest.read_text())['files']:
            candidate=(OUT/item).resolve()
            if candidate.is_relative_to(OUT) and candidate.is_file():candidate.unlink()
    for path in (ROOT/'site').rglob('*'):
        if path.is_file():
            target=OUT/path.relative_to(ROOT/'site');target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(path,target)
    docs=[]
    for index,path in enumerate(SOURCES,1):
        text=path.read_text(encoding='utf-8')
        title=next((line.lstrip('# ').strip() for line in text.splitlines() if line.startswith('# ')),path.name)
        if path.name=='LICENSE':title='저작권과 이용 정책'
        category='상세 설계' if '/design/' in str(path) else '제작·운영' if '/production/' in str(path) else '프로젝트 기준'
        route=ROUTES[path.resolve()]
        page=f'''<!doctype html><html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>{html.escape(title)} · Raise a Healthy Game</title><link rel="stylesheet" href="../assets/style.css"></head><body class="reader-body"><a class="skip" href="#document">본문 바로가기</a><header class="reader-top"><a href="../index.html#library">← 설계 문서 서재</a><span>RAISE A HEALTHY GAME · 진우주</span></header><article class="reader" id="document"><div class="reader-meta">설계 v0.2 · 기획 수치/콘텐츠는 검증 전 계획입니다 · <a href="{REPO}/blob/main/{path.relative_to(ROOT).as_posix()}">GitHub 원문 ↗</a></div>{markdown(text,path)}</article><div class="reader-footer">© 2026 진우주. All rights reserved. <a href="../index.html">설계실로 돌아가기 →</a></div></body></html>'''
        target=OUT/route;target.parent.mkdir(parents=True,exist_ok=True);target.write_text(page,encoding='utf-8')
        docs.append(dict(index=index,title=title,category=category,href=route,text=text))
    for folder in ['catalog','balance','examples']:
        for path in (ROOT/'data'/folder).glob('*.json'):
            if '.archive.' in path.name:continue
            target=OUT/path.relative_to(ROOT);target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(path,target)
    data=dict(docs=docs,atlas=json.loads((ROOT/'data/catalog/body-atlas.v0.2.json').read_text()),levels=json.loads((ROOT/'data/balance/levels.v0.2.json').read_text()),project=json.loads((ROOT/'data/catalog/project.v0.2.json').read_text()))
    (OUT/'catalog.js').write_text('window.DESIGN_DATA = '+json.dumps(data,ensure_ascii=False).replace('</','<\\/')+';\n',encoding='utf-8')
    (OUT/'.nojekyll').write_text('')
    files=sorted(p.relative_to(OUT).as_posix() for p in OUT.rglob('*') if p.is_file() and p.name!='build-manifest.json')
    manifest.write_text(json.dumps(dict(version='0.2',files=files,documents=len(docs),atlasEntries=len(data['atlas']['entries'])),ensure_ascii=False,indent=2)+'\n')
    print(f'Built {len(docs)} document pages; {len(files)} files; {len(data["atlas"]["entries"])} atlas topics.')

if __name__=='__main__':main()
